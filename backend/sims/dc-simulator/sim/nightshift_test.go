func TestNightShiftCaptureDrift(t *testing.T) {
	// This reads outside the module: Go's test cache cannot track the fixture.
	// Run with -count=1 (as CI does).
	dir := filepath.FromSlash("../../../services/event-processing/internal/review/testdata")
	raw, err := GenerateNightShiftCapture()
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile(filepath.Join(dir, "night-shift.capture.sha256"))
	if err != nil {
		t.Fatal(err)
	}
	compressed, err := os.ReadFile(filepath.Join(dir, "night-shift.capture.jsonl.gz"))
	if err != nil {
		t.Fatal(err)
	}
	z, err := gzip.NewReader(bytes.NewReader(compressed))
	if err != nil {
		t.Fatal(err)
	}
	golden, err := io.ReadAll(z)
	if err != nil {
		t.Fatal(err)
	}
	if err := z.Close(); err != nil {
		t.Fatal(err)
	}
	for label, data := range map[string][]byte{"generated": raw, "decompressed": golden} {
		if got := fmt.Sprintf("%x", sha256.Sum256(data)); got != strings.TrimSpace(string(want)) {
			t.Errorf("%s hash %s != %s", label, got, want)
		}
	}
	if !bytes.Equal(raw, golden) {
		t.Fatal("generated bytes differ from golden")
	}
}

type nightMargins struct{ max5, max15, first5, first15, plateau, above5, controlHot float64 }

func measureNight(t *testing.T, r nightShiftRun) map[string]nightMargins {
	t.Helper()
	out := map[string]nightMargins{}
	a5, a15 := map[string]*SlidingAverage{}, map[string]*SlidingAverage{}
	plateauRun := map[string]float64{}
	for _, e := range r.events {
		second := e.At.Sub(nightShiftEpoch).Seconds()
		occ, _ := e.Metrics[TowerpulseOccupancyKey].Float64()
		temp, _ := e.Metrics[TowerpulseTempKey].Float64()
		if a5[e.Device] == nil {
			a5[e.Device] = &SlidingAverage{}
			a15[e.Device] = &SlidingAverage{}
			out[e.Device] = nightMargins{first5: -1, first15: -1}
		}
		if occ <= 0 {
			continue
		}
		m := out[e.Device]
		avg5 := a5[e.Device].Add(second, temp, 300)
		avg15 := a15[e.Device].Add(second, temp, 900)
		if e.Device == NightShiftNormal && second >= 135*60 && avg5 >= 25 {
			t.Fatalf("normal five-minute average stayed warm at %gs: %g", second, avg5)
		}
		if e.Device == NightShiftIncident && temp > 25.85 {
			t.Fatalf("incident instantaneous temperature exceeded cap: %g", temp)
		}
		m.max5 = max(m.max5, avg5)
		m.max15 = max(m.max15, avg15)
		if avg5 > 25.5 && m.first5 < 0 {
			m.first5 = second / 60
		}
		if avg15 > 25.65 && m.first15 < 0 {
			m.first15 = second / 60
		}
		if second >= 45*60 && second < 95*60 && avg5 >= 25.75 && avg5 <= 25.85 {
			plateauRun[e.Device] += DefaultEmitInterval.Minutes()
			m.plateau = max(m.plateau, plateauRun[e.Device])
		} else {
			plateauRun[e.Device] = 0
		}
		if second >= 120*60 && avg5 > 25.5 {
			m.above5 += DefaultEmitInterval.Minutes()
		}
		if second >= 105*60 && second < 160*60 && avg5 > 26.3 {
			m.controlHot += DefaultEmitInterval.Minutes()
		}
		out[e.Device] = m
	}
	return out
}
func TestNightShiftMarginsAndFeedback(t *testing.T) {
	closed, err := runNightShift(true)
	if err != nil {
		t.Fatal(err)
	}
	open, err := runNightShift(false)
	if err != nil {
		t.Fatal(err)
	}
	margins := measureNight(t, closed)
	unboosted := measureNight(t, open)
	for _, dev := range []string{NightShiftIncident, NightShiftNormal, NightShiftControl} {
		t.Logf("%s: %+v", dev, margins[dev])
	}
	t.Logf("unboosted control: %+v; commands: %+v; edges: %+v", unboosted[NightShiftControl], closed.commands, closed.edges)
	incident := margins[NightShiftIncident]
	if incident.max5 > 25.85 || incident.max5 < 25.75 || incident.plateau < 25 || incident.first5 < 45 || incident.first5 > 70 || incident.first15 < 45 || incident.first15 > 70 {
		t.Errorf("incident margins: %+v", incident)
	}
	normal := margins[NightShiftNormal]
	if normal.max5 < 25.7 || normal.max5 > 25.8 || normal.above5 > 7 || normal.above5 <= 0 || normal.max15 > 25.3 || normal.first5 < 120 {
		t.Errorf("normal margins: %+v", normal)
	}
	if unboosted[NightShiftControl].controlHot < 10 {
		t.Error("control absent boost is not hot for 10 minutes")
	}
	for _, dev := range NightShiftDevices() {
		count := 0
		for _, e := range closed.events {
			if e.Device != dev {
				continue
			}
			minute := e.At.Sub(nightShiftEpoch).Minutes()
			occ, _ := e.Metrics[TowerpulseOccupancyKey].Float64()
			temp, _ := e.Metrics[TowerpulseTempKey].Float64()
			if minute >= 10 && minute < 45 {
				if occ <= 0 || temp < 22.7 || temp > 22.9 {
					t.Fatalf("settle %s at %g: %v", dev, minute, e.Metrics)
				}
				count++
			}
			if (dev == "tp-vav-tower-f1-north" || dev == "tp-vav-tower-f3-south") && minute >= 10 && (occ <= 0 || temp > 23) {
				t.Fatalf("bystander warmed: %+v", e)
			}
			if dev == NightShiftNormal && minute >= 135 && temp >= 25 {
				t.Fatalf("normal did not cool below 25: %+v", e)
			}
			if dev == NightShiftIncident && minute >= 46 && minute < 95 {
				set, _ := e.Metrics[TowerpulseSetpointKey].Float64()
				if occ != 3 || set != 24 {
					t.Fatal("incident people/setpoint", e)
				}
			}
		}
		if float64(count)*DefaultEmitInterval.Minutes() < 30 {
			t.Errorf("%s lacks 30 minutes of occupied settle samples", dev)
		}
	}
	// Re-evaluate the delivered samples independently: exactly one accepted command
	// per raise, in edge order, and none for out-of-set telemetry.
	oracle, err := newR1Oracle()
	if err != nil {
		t.Fatal(err)
	}
	var expected []oracleCommand
	for _, e := range closed.events {
		metrics := map[string]float64{}
		for k, v := range e.Metrics {
			metrics[k], _ = v.Float64()
		}
		second := e.At.Sub(nightShiftEpoch).Seconds()
		if changed, raised := oracle.sample(e.Device, second, metrics); changed && raised {
			expected = append(expected, oracleCommand{"oracle", e.Device, e.At, e.At.Add(2 * time.Second), TowerpulseBoostCommandKey, json.RawMessage(`{"minutes":15}`)})
		}
	}
	a, _ := json.Marshal(expected)
	b, _ := json.Marshal(closed.commands)
	if !bytes.Equal(a, b) {
		t.Fatalf("boosts differ from rises: %s vs %s", a, b)
	}
	if len(expected) == 0 {
		t.Fatal("no baseline control boost")
	}
	for _, c := range expected {
		minute := c.RaisedAt.Sub(nightShiftEpoch).Minutes()
		if c.Device != NightShiftControl || minute < 105 || minute >= 160 {
			t.Errorf("unexpected boost: %+v", c)
		}
	}
	if bytes.Equal(closed.bytes, open.bytes) {
		t.Fatal("oracle feedback did not alter later physics")
	}
	outside := 0
	for _, e := range closed.events {
		if e.Device == NightShiftBystander {
			outside++
		}
	}
	if outside != int(165*time.Minute/DefaultEmitInterval)+1 {
		t.Fatalf("out-of-set device has %d samples", outside)
	}
}

func TestNightShiftEpisodeValidation(t *testing.T) {
	for _, tc := range []struct {
		manifest, episode string
		bad               bool
	}{{"towerpulse", "", false}, {"towerpulse", "classic", false}, {"towerpulse", "night-shift", false}, {"towerpulse", "typo", true}, {"sitepulse", "night-shift", true}} {
		_, err := NewSimEpisode(tc.manifest, tc.episode, 1, Load{})
		if (err != nil) != tc.bad {
			t.Errorf("%+v: %v", tc, err)
		}
	}
}
