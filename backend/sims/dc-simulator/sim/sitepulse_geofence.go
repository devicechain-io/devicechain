// The site's geographic origin: Unity site-local (0, 0), the terrain centre, with X east
// and Z north in metres (the scene's terrain generator, quarry_heightmap.py). Every
// geographic position in this scenario is derived from it by the small-area conversion
//
//	latitude  = originLatitude  + north / R * 180/pi
//	longitude = originLongitude + east / (R * cos(originLatitude)) * 180/pi
//
// with R = 6371000 m. The origin is open high desert in central Nevada: plausible
// hard-rock terrain, far enough from the poles that the longitude scale holds, and over
// no town on a real basemap. It is the SHARED half of a contract with the Unity player,
// which must convert its location reports with the same origin and formula; if the two
// disagree, the platform's fence and the machine positions it is tested against differ by
// however far apart the origins are, and nothing on either side says so.
//
// The ring below is literals, not a computation over these constants, so the manifest is
// deterministic; the test re-derives it from its own copy of the origin and asserts these constants equal that copy.
const (
	sitepulseOriginLatitude  = 39.0
	sitepulseOriginLongitude = -117.0
)

const (
	// SitepulsePitGeofenceToken names the pit geofence.
	SitepulsePitGeofenceToken = "sp-geofence-pit"
	sitepulsePitGeofenceName  = "Pit"
)

// sitepulseGeoFences is the site's geofences, freshly built per call for the reason
// sitepulseAreas is: a manifest is handed to callers, and a shared backing array makes
// one caller's write everyone's.
//
// The platform has no first-class link from a fence to an area, so the only tie to the
// excavation zone is the description. It says what the fence IS, because area
// membership and fence containment differ here: the zone's crusher plant stands outside
// the pit.
func sitepulseGeoFences() []GeoFenceSpec {
	ring := make([][2]float64, len(sitepulsePitRing))
	copy(ring, sitepulsePitRing[:])
	return []GeoFenceSpec{{
		Token: SitepulsePitGeofenceToken,
		Name:  sitepulsePitGeofenceName,
		Description: "The pit rim: about 4 m outside the last cut ground of the excavation in zone " +
			SitepulseZoneCutToken + ". A boundary of the pit, not of the zone (the zone's crusher plant is outside it).",
		Ring: ring,
	}}
}

