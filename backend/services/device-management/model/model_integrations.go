// IntegrationType is the kind of sender an inbound integration authenticates, and therefore
// the body format the ingest route parses for it. It is fixed when the integration is
// created: the codec for a route is the integration's REGISTERED type, never guessed from a
// body, so changing it would re-interpret traffic from a sender that has not changed.
type IntegrationType string

const (
	// IntegrationChirpStackV4 is a ChirpStack v4 network server's JSON HTTP integration.
	IntegrationChirpStackV4 IntegrationType = "CHIRPSTACK_V4"
	// IntegrationTTSV3 is a The Things Stack v3 webhook.
	IntegrationTTSV3 IntegrationType = "TTS_V3"
	// IntegrationGenericJSON is any sender of JSON, with the device id, an optional item
	// array and an optional time named by the integration's generic settings.
	IntegrationGenericJSON IntegrationType = "GENERIC_JSON"
	// IntegrationGenericBinary is any sender of a binary body, identified by a header or a
	// query parameter.
	IntegrationGenericBinary IntegrationType = "GENERIC_BINARY"
)

// Valid reports whether the type names one of the known integration types.
func (t IntegrationType) Valid() bool {
	switch t {
	case IntegrationChirpStackV4, IntegrationTTSV3, IntegrationGenericJSON, IntegrationGenericBinary:
		return true
	default:
		return false
	}
}

// IsGeneric reports whether the type is one of the two generic senders, which are the ones
// that name their own identity and that carry generic settings.
func (t IntegrationType) IsGeneric() bool {
	return t == IntegrationGenericJSON || t == IntegrationGenericBinary
}

// String returns the underlying string value.
func (t IntegrationType) String() string { return string(t) }

// The identity an integration resolves a device by. A LoRaWAN network server names a device
// by its DevEUI or its own device id; a generic sender names it with an alias scheme the
// tenant chose.
const (
	// IntegrationIdentityDevEUI resolves by the DevEUI, through the lorawan.deveui alias
	// scheme. The default for the two network-server types.
	IntegrationIdentityDevEUI = "DEV_EUI"
	// IntegrationIdentityDeviceID resolves by The Things Stack's device id, through the
	// tts.device-id alias scheme.
	IntegrationIdentityDeviceID = "DEVICE_ID"
	// IntegrationIdentityAliasPrefix prefixes a generic sender's alias scheme:
	// "ALIAS:custom.<name>".
	IntegrationIdentityAliasPrefix = "ALIAS:"
)

// Integration is an inbound integration: a tenant resource that holds the bearer token a
// network server or a webhook sender presents at an ingest route, the type of body it sends,
// and the device types it may resolve devices of.
//
// 🔴 THE TOKEN IS NEVER STORED, ONLY ITS KEYED DIGEST. TokenDigest is what
// credential.DeriveEnrollmentSecretKeys's Integration key made of the token that
// CreateIntegration or RotateIntegrationToken generated; nothing that reads this row can
// recover it. A presented token is compared in constant time through the credential Checker
// under KindIntegration (AuthenticateIntegration). The token is generated by the server from
// 256 random bits, so it needs no per-key backoff: nothing can be guessed online.
//
// 🔴 THE SCOPE IS THE DEVICE TYPES, NOT THE TENANT. An integration resolves only devices
// whose type is one of its DeviceTypes, so a token that leaks, or a sender that is wrong
// about a DevEUI, cannot reach a device of another kind. The link is a join table with a
// foreign key that REFUSES deleting a device type an integration is scoped to.
//
// The integration is deliberately not customer-scopable: it declares no scope rule, so a
// caller whose access is limited to part of the tenant is refused at the store.
type Integration struct {
	gorm.Model
	rdb.TenantScoped
	rdb.TokenReference
	rdb.NamedEntity
	rdb.MetadataEntity

	// Type is an IntegrationType, immutable after create.
	Type    string `gorm:"not null;size:32"`
	Enabled bool   `gorm:"not null"`
	// Identity is how the sender names a device: IntegrationIdentityDevEUI,
	// IntegrationIdentityDeviceID, or "ALIAS:<scheme>" for a generic sender.
	Identity string `gorm:"not null;size:128"`
	// Generic holds a generic sender's settings (the integration's own JSON document, see
	// GenericIntegrationSettings), NULL for the network-server types.
	Generic *datatypes.JSON
	// LinkMetrics adds the receive-link readings (signal strength, signal-to-noise ratio,
	// gateway count) beside the decoded values, when the sender reports them.
	LinkMetrics bool `gorm:"not null"`

	// TokenDigest is the keyed digest of the bearer token.
	TokenDigest string `gorm:"not null;size:128"`
	// TokenIssuedAt is when the token was last generated: at create, and at every rotation.
	TokenIssuedAt time.Time `gorm:"not null"`

	// The markers below are written by the ingest path, at most once a minute, so an
	// operator can see that a sender is reaching the platform but delivering nothing usable.
	// They are zero until that path exists.

	// UndecodedCount counts uplinks accepted with no decoded object to read readings from.
	UndecodedCount int64 `gorm:"not null;default:0"`
	// LastUndecodedAt is when the last one arrived.
	LastUndecodedAt sql.NullTime
	// LastUndecodedSample is up to 512 bytes of that frame, hex encoded.
	LastUndecodedSample sql.NullString `gorm:"size:1024"`
	// LastAuthFailureAt is when a request for this integration last failed authentication.
	LastAuthFailureAt sql.NullTime

	// DeviceTypes is the scope, loaded by the API (it is not a column). Every integration
	// read through the API carries it.
	DeviceTypes []*DeviceType `gorm:"-"`

	// IssuedToken is the bearer token as generated, on the row a create or a rotate just
	// wrote, and "" on every row read from the database. It is not a column. The response to
	// the write that minted it shows it, once; nothing can show it again.
	IssuedToken string `gorm:"-"`
}

// DefaultOrder implements rdb.Sortable: newest first, token as the unique tiebreak.
func (Integration) DefaultOrder() string {
	return "integrations.created_at DESC, integrations.token ASC"
}

// IntegrationDeviceType is one device type in an integration's scope. It is a plain join row,
// hard-deleted with its integration (the foreign key cascades) and never soft-deleted. Its
// device type foreign key has NO cascade, which is what refuses deleting a type an
// integration is scoped to.
type IntegrationDeviceType struct {
	ID            uint `gorm:"primarykey"`
	CreatedAt     time.Time
	TenantId      string `gorm:"index;not null;size:128"`
	IntegrationId uint   `gorm:"not null;uniqueIndex:uix_integration_device_types_pair,priority:1"`
	DeviceTypeId  uint   `gorm:"not null;index;uniqueIndex:uix_integration_device_types_pair,priority:2"`
}

// Data required to create an integration.
//
// There is no bearer token: the server generates it (256 bits) and returns it once, as the
// created integration's IssuedToken. A token an operator chose is a token somebody else may
// also know.
type IntegrationCreateRequest struct {
	Token       string
	Name        *string
	Description *string
	// Type is an IntegrationType.
	Type    string `gorm:"not null;size:32"`
	Enabled bool   `gorm:"not null"`
	// DeviceTypeTokens is the scope: at least one device type.
	DeviceTypeTokens []string
	// Identity defaults to DEV_EUI for the network-server types and is required, as an
	// ALIAS:custom.<name>, for the generic ones.
	Identity *string
	// Generic is the generic sender's settings as a JSON object. Required for the generic
	// types and refused for the others.
	Generic *string
	// LinkMetrics defaults to false.
	LinkMetrics *bool
	Metadata    *string
}

// A PARTIAL update to an integration: omit a field to leave the stored value alone, send null
// to clear a nullable one, send a value to set it. There is no Token (the integration is
// identified by the mutation's `token` argument) and no Type (the codec of a route is fixed
// when the integration is created). The bearer token changes only through
// RotateIntegrationToken, so no edit can blank it or replace it with a guessable one.
type IntegrationUpdateRequest struct {
	Name        dcgraphql.OptionalString
	Description dcgraphql.OptionalString
	// Enabled is a NOT NULL column; a null is refused.
	Enabled dcgraphql.OptionalBool
	// DeviceTypeTokens replaces the scope. A null or an empty list is refused: an integration
	// with no scope resolves nothing, and disabling it is what stops it.
	DeviceTypeTokens dcgraphql.OptionalStringList
	// Identity is a NOT NULL column; a null is refused. It is validated against the type.
	Identity dcgraphql.OptionalString
	// Generic replaces the generic settings. It is required for a generic type (a null is
	// refused) and refused for the network-server types, which hold none.
	Generic     dcgraphql.OptionalString
	LinkMetrics dcgraphql.OptionalBool
	Metadata    dcgraphql.OptionalString
}

// Search criteria for locating integrations.
type IntegrationSearchCriteria struct {
	rdb.Pagination
	Type    *string
	Enabled *bool
	// DeviceType is the token of a device type the integration's scope must include.
	DeviceType *string
}

// Results for integration search.
type IntegrationSearchResults struct {
	Results    []Integration
	Pagination rdb.SearchResultsPagination
}
