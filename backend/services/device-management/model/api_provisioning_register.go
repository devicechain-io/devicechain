// This file is the model half of device self-registration: authenticating a provisioning
// profile's shared secret, and registering one device against it. The HTTP endpoint that calls
// them owns the transport concerns (the read deadline, the body cap, the slot bound, the
// per-source and per-tenant buckets) and maps the closed set of refusals below onto status
// codes; everything that decides WHAT happens to a device lives here, so that the decision is
// tested through the model and not through a handler.

// The closed vocabulary of ways a registration is refused. Each code is a wire code the
// endpoint serves; the set is pinned by a golden test, and a code is never added without the
// endpoint's contract and its docs.
const (
	ProvisioningCodeFailed              = "PROVISIONING_FAILED"
	ProvisioningCodeInvalid             = "INVALID_VALUE"
	ProvisioningCodeNotRegistered       = "DEVICE_NOT_REGISTERED"
	ProvisioningCodeNotEarmarked        = "DEVICE_NOT_EARMARKED"
	ProvisioningCodeDeviceDisabled      = "DEVICE_DISABLED"
	ProvisioningCodeTypeMismatch        = "DEVICE_TYPE_MISMATCH"
	ProvisioningCodeTokenCollision      = "DEVICE_TOKEN_COLLISION"
	ProvisioningCodeAlreadyProvisioned  = "ALREADY_PROVISIONED"
	ProvisioningCodeLimitExceeded       = "LIMIT_EXCEEDED"
	ProvisioningCodeUnavailable         = "PROVISIONING_UNAVAILABLE"
	ProvisioningCodeMisconfigured       = "PROVISIONING_MISCONFIGURED"
	ProvisioningCodeCredentialTypeUnsup = "CREDENTIAL_TYPE_UNSUPPORTED"
)

// ProvisioningRefusal is one refusal of a registration. Its Code and Reason are what the
// endpoint serves and its HTTPStatus is the status that goes with them; its message is
// generic by construction. Where several causes share a code on purpose (every way
// authentication can fail is one PROVISIONING_FAILED), nothing in the message says which.
type ProvisioningRefusal struct {
	// Code is one of the ProvisioningCode constants.
	Code string
	// HTTPStatus is the status the endpoint answers with.
	HTTPStatus int
	// Reason refines ALREADY_PROVISIONED: "revoked" for a credential an operator disabled, which
	// stays refused until the device is reset. Empty otherwise.
	Reason string
	msg    string
}

func (e *ProvisioningRefusal) Error() string { return e.msg }

// Is matches on the code (and the reason, when the target names one), so
// errors.Is(err, ErrProvisioningAlreadyProvisioned) is true of both reasons while
// errors.Is(err, ErrProvisioningRevoked) is true only of the revoked one.
func (e *ProvisioningRefusal) Is(target error) bool {
	t, ok := target.(*ProvisioningRefusal)
	return ok && t.Code == e.Code && (t.Reason == "" || t.Reason == e.Reason)
}

// The refusals. Their messages are the whole text a device is shown.
var (
	// ErrProvisioningFailed is every way authentication can fail and a few that look like it: an
	// unknown tenant, key or secret; a profile that is disabled, expired, or whose secret was
	// never generated by the server; a tenant being erased. They are one answer on purpose, so
	// that the response never tells a stranger which of them holds.
	ErrProvisioningFailed = &ProvisioningRefusal{Code: ProvisioningCodeFailed, HTTPStatus: 401,
		msg: "provisioning failed: the provision key or secret is not valid"}
	// ErrProvisioningNotRegistered is an unknown device under CHECK_PRE_PROVISIONED.
	ErrProvisioningNotRegistered = &ProvisioningRefusal{Code: ProvisioningCodeNotRegistered, HTTPStatus: 404,
		msg: "no device is registered for this external id"}
	// ErrProvisioningNotEarmarked is a device this profile may not adopt: it was not earmarked
	// for it. Under either strategy.
	ErrProvisioningNotEarmarked = &ProvisioningRefusal{Code: ProvisioningCodeNotEarmarked, HTTPStatus: 409,
		msg: "the device is not earmarked for this provisioning profile"}
	// ErrProvisioningDeviceDisabled is a disabled device.
	ErrProvisioningDeviceDisabled = &ProvisioningRefusal{Code: ProvisioningCodeDeviceDisabled, HTTPStatus: 403,
		msg: "the device is disabled"}
	// ErrProvisioningTypeMismatch is a device whose type is not the profile's.
	ErrProvisioningTypeMismatch = &ProvisioningRefusal{Code: ProvisioningCodeTypeMismatch, HTTPStatus: 409,
		msg: "the device is not of the provisioning profile's device type"}
	// ErrProvisioningTokenCollision is a derived device token already held by another device.
	ErrProvisioningTokenCollision = &ProvisioningRefusal{Code: ProvisioningCodeTokenCollision, HTTPStatus: 409,
		msg: "the device token derived for this external id is already held by another device"}
	// ErrProvisioningAlreadyProvisioned is a device that already holds a credential and whose
	// presented material is not an exact replay of this profile's own issuance.
	ErrProvisioningAlreadyProvisioned = &ProvisioningRefusal{Code: ProvisioningCodeAlreadyProvisioned, HTTPStatus: 409,
		msg: "the device already holds a credential"}
	// ErrProvisioningRevoked is ErrProvisioningAlreadyProvisioned for a credential this profile
	// issued that an operator has since disabled. Revocation sticks until an explicit reset.
	ErrProvisioningRevoked = &ProvisioningRefusal{Code: ProvisioningCodeAlreadyProvisioned, HTTPStatus: 409, Reason: "revoked",
		msg: "the device's credential was revoked; an operator must reset its provisioning"}
	// ErrProvisioningLimitExceeded is a registration that would take the profile past its
	// maxDevices.
	ErrProvisioningLimitExceeded = &ProvisioningRefusal{Code: ProvisioningCodeLimitExceeded, HTTPStatus: 422,
		msg: "the provisioning profile has registered as many devices as it allows"}
	// ErrProvisioningUnavailable is self-registration with no keys to compare under.
	ErrProvisioningUnavailable = &ProvisioningRefusal{Code: ProvisioningCodeUnavailable, HTTPStatus: 503,
		msg: "device self-registration is not available on this instance"}
	// ErrProvisioningMisconfigured is a profile that cannot register anything: a device type
	// that was deleted, or a strategy that is not in the vocabulary. It is the operator's to fix.
	ErrProvisioningMisconfigured = &ProvisioningRefusal{Code: ProvisioningCodeMisconfigured, HTTPStatus: 500,
		msg: "the provisioning profile is misconfigured"}
	// ErrProvisioningCredentialTypeUnsupported is a profile that mints a credential type this
	// build cannot. Terminal, and never falls back to another type.
	ErrProvisioningCredentialTypeUnsupported = &ProvisioningRefusal{Code: ProvisioningCodeCredentialTypeUnsup, HTTPStatus: 501,
		msg: "the provisioning profile mints a credential type this build does not support"}
)

// invalidProvisioning is INVALID_VALUE naming the field that is wrong (never its value: the
// material is a credential).
func invalidProvisioning(format string, args ...any) *ProvisioningRefusal {
	return &ProvisioningRefusal{Code: ProvisioningCodeInvalid, HTTPStatus: 400, msg: fmt.Sprintf(format, args...)}
}

// The material a device presents: a base64url string (RFC 4648 section 5, no padding), 22 to
// 256 characters. The floor is 128 bits of entropy at the alphabet's 6 bits a character; the
// ceiling is credential.MaxAccessTokenBytes, the width of the credential id column.
const (
	ProvisioningMaterialMin = 22
	ProvisioningMaterialMax = credential.MaxAccessTokenBytes
)

// ValidateProvisioningMaterial reports why material cannot be a device's registration
// material, or nil. It never echoes the material.
func ValidateProvisioningMaterial(material string) error {
	if n := len(material); n < ProvisioningMaterialMin || n > ProvisioningMaterialMax {
		return invalidProvisioning("credentialSecret must be %d to %d characters", ProvisioningMaterialMin, ProvisioningMaterialMax)
	}
	for i := 0; i < len(material); i++ {
		c := material[i]
		switch {
		case c >= 'A' && c <= 'Z', c >= 'a' && c <= 'z', c >= '0' && c <= '9', c == '-', c == '_':
		default:
			return invalidProvisioning("credentialSecret must be base64url: only letters, digits, '-' and '_'")
		}
	}
	return nil
}

// profileCanRegister reports whether a profile may register a device now: enabled, not past
// its expiry, and carrying a secret the server generated. It is the one definition, shared by
// authentication and by the check under the profile's lock.
func profileCanRegister(p *ProvisioningProfile, now time.Time) bool {
	if !p.Enabled || !p.ProvisionSecretIssued || !p.ProvisionSecretDigest.Valid {
		return false
	}
	return !p.ExpiresAt.Valid || p.ExpiresAt.Time.After(now)
}

// AuthenticateProvisioningProfile proves the presented provision secret belongs to the profile
// with the presented key, in the tenant of ctx, and returns the profile. Every failure is
// ErrProvisioningFailed and costs the same: a key that names nothing, and a profile that is
// disabled, expired or unmarked, are compared against the Checker's dummy digest, so the answer
// and the work are the same whether the profile exists.
//
// The compare is the credential Checker's, under KindProvisioningProfile, bound to the tenant:
// a digest transplanted from another tenant's row verifies nothing. The secret is never
// compared here.
//
// The returned profile is what ProvisionDevice is handed. It carries the digest that was
// verified, so a rotation between the two is noticed (ProvisionDevice re-reads the row under
// its lock and refuses a different digest).
func (api *Api) AuthenticateProvisioningProfile(ctx context.Context, provisionKey, secret string) (*ProvisioningProfile, error) {
	if api.ProvisioningChecker == nil || api.EnrollmentKeys == nil {
		return nil, ErrProvisioningUnavailable
	}
	tenant, err := ctxTenant(ctx)
	if err != nil {
		return nil, err
	}
	var matched *ProvisioningProfile
	lookup := func(ctx context.Context) (string, error) {
		var found ProvisioningProfile
		err := api.RDB.DB(ctx).Where("provision_key = ?", provisionKey).First(&found).Error
		switch {
		case errors.Is(err, gorm.ErrRecordNotFound):
			return "", nil
		case err != nil:
			return "", err
		case !profileCanRegister(&found, time.Now()):
			return "", nil
		}
		matched = &found
		return found.ProvisionSecretDigest.String, nil
	}
	err = api.ProvisioningChecker.Check(ctx, credential.Principal{
		Kind: credential.KindProvisioningProfile, ID: tenant + ":" + provisionKey, Tenant: tenant,
	}, secret, lookup)
	switch {
	case err == nil && matched != nil:
		return matched, nil
	case err == nil, errors.Is(err, credential.ErrMismatch):
		return nil, ErrProvisioningFailed
	default:
		return nil, err
	}
}

// ProvisionOutcome is what a successful registration did.
type ProvisionOutcome string

const (
	// ProvisionCreated: the device did not exist (ALLOW_NEW) and was created with its credential.
	ProvisionCreated ProvisionOutcome = "CREATED"
	// ProvisionAdopted: an earmarked device that held no credential was given one.
	ProvisionAdopted ProvisionOutcome = "ADOPTED"
	// ProvisionReplayed: the device already held this profile's credential and presented the same
	// material again. Nothing was written.
	ProvisionReplayed ProvisionOutcome = "REPLAYED"
)

// ProvisionRequest is one registration, after the profile has been authenticated.
type ProvisionRequest struct {
	// Profile is the profile AuthenticateProvisioningProfile returned.
	Profile *ProvisioningProfile
	// ExternalId names the device, as the device calls itself (a serial number). It is the
	// lookup key; the device's token is derived from it when the device is created.
	ExternalId string
	// CredentialSecret is the device's own material, which becomes its access token. The platform
	// stores only its digest. See ValidateProvisioningMaterial.
	CredentialSecret string
	// Name and Metadata are optional and apply only to a device this call creates.
	Name     *string
	Metadata *string
}

// ProvisionResult holds nothing secret: not the material, and not the credential's id.
type ProvisionResult struct {
	Outcome        ProvisionOutcome
	Tenant         string
	DeviceToken    string
	ExternalId     string
	CredentialType string
}

// provisionedDeviceTokenPrefix and provisionedCredentialTokenPrefix namespace the tokens
// self-registration derives, so an operator reading "pv-" knows where a device came from.
const (
	provisionedDeviceTokenPrefix     = "pv-"
	provisionedCredentialTokenPrefix = "pc-"
)

// ProvisionDevice registers one device against an authenticated provisioning profile.
//
// # What it decides
//
// A known device is judged by these steps in order, and the FIRST that matches is the answer.
// Every refusal comes before any write:
//
//  1. the device is disabled                                    -> ErrProvisioningDeviceDisabled
//  2. its type is not the profile's                             -> ErrProvisioningTypeMismatch
//  3. it is not earmarked for this profile                      -> ErrProvisioningNotEarmarked
//  4. this profile's credential on it was disabled or expired   -> ErrProvisioningRevoked
//  5. it holds this profile's live credential and the material
//     presented is the same                                     -> REPLAYED, nothing written
//  6. it holds this profile's live credential and the material
//     differs, or any other credential                          -> ErrProvisioningAlreadyProvisioned
//  7. it holds no credential and the profile is at maxDevices   -> ErrProvisioningLimitExceeded
//  8. otherwise                                                 -> ADOPTED
//
// A device that does not exist is a 404 under CHECK_PRE_PROVISIONED, and under ALLOW_NEW is
// created (at the cap, ErrProvisioningLimitExceeded), earmarked for the profile and of its type.
// ALLOW_NEW never adopts a device that was not earmarked for it: an operator-made device is
// only ever taken over by a profile somebody pointed at it.
//
// # Locks
//
// The profile row is locked FIRST, then the device row. Every path that touches both takes them
// in that order (revoke, reset and delete lock the profile first), and the profile lock also
// serializes every registration against one profile, which is what makes the maxDevices count
// exact: it is counted under the lock, so twenty concurrent registrations against a cap of five
// admit five.
//
// A unique violation is never resolved inside the transaction it aborts. It rolls back and the
// registration is retried ONCE in a fresh transaction, where the re-read sees the winner and
// decides normally (a REPLAYED, a refusal). A second violation is a 409.
//
// # What it does not do
//
// It does not authenticate (AuthenticateProvisioningProfile does) and it does not rate-limit.
// It re-checks only that the profile it was handed is still able to register under the lock.
func (api *Api) ProvisionDevice(ctx context.Context, request *ProvisionRequest) (*ProvisionResult, error) {
	if api.ProvisioningChecker == nil || api.DeviceSecretKey == nil || api.EnrollmentKeys == nil {
		return nil, ErrProvisioningUnavailable
	}
	tenant, err := ctxTenant(ctx)
	if err != nil {
		return nil, err
	}
	if request == nil || request.Profile == nil {
		return nil, errors.New("a registration needs the authenticated provisioning profile")
	}
	if err := validateProvisionRequest(request); err != nil {
		return nil, err
	}
	actor := "provisioning-profile:" + request.Profile.Token
	ctx = rdb.WithAuditActor(ctx, actor)

	var done *provisionDone
	for attempt := 0; ; attempt++ {
		done, err = api.provisionOnce(ctx, tenant, request)
		if err == nil || !conflict.Is(err) {
			break
		}
		if attempt == 1 {
			// A second unique violation in a row: the writers are racing faster than the
			// re-read can settle, or the material collides with a credential nobody here owns.
			return nil, classifyProvisionConflict(tenant, request, err)
		}
	}
	if err != nil {
		return nil, mapProvisionError(err)
	}

	result := &ProvisionResult{
		Outcome: done.outcome, Tenant: tenant, DeviceToken: done.device.Token,
		ExternalId: request.ExternalId, CredentialType: string(CredentialAccessToken),
	}
	if done.outcome == ProvisionReplayed {
		// A replay writes nothing, so the write-time fence never ran. A tenant whose erasure
		// has begun must not be told its device is registered.
		if err := rdb.CheckTenantFence(ctx, api.RDB.Database, tenant); err != nil {
			return nil, mapProvisionError(err)
		}
		return result, nil
	}

	// CREATED and ADOPTED are audited, once each. A REPLAYED is counter-only: a device that
	// retries on a lost response or reboots in a loop must not fill the journal, and a replay
	// changes nothing. The audit write is best-effort, like every authentication event.
	if aerr := api.RDB.RecordAuthEventLabeled(ctx, "device.provision."+strings.ToLower(string(done.outcome)),
		actor, tenant, done.device.Token); aerr != nil {
		log.Warn().Err(aerr).Str("tenant", tenant).Str("device", done.device.Token).
			Msg("Could not journal a device self-registration.")
	}
	api.evictDeviceCredentials(ctx, tenant, done.device.ID)
	if done.outcome == ProvisionCreated {
		api.emitDeviceRosterForDevice(ctx, done.device, false)
	}
	return result, nil
}

// validateProvisionRequest checks everything about a registration that its own fields decide,
// before a transaction opens. The endpoint checks the same things before it takes a slot, so
// this is the model refusing on its own what no caller should send.
func validateProvisionRequest(request *ProvisionRequest) error {
	if err := ValidateProvisioningMaterial(request.CredentialSecret); err != nil {
		return err
	}
	ext := request.ExternalId
	if strings.TrimSpace(ext) == "" || utf8.RuneCountInString(ext) > maxDeviceExternalIdLen || strings.ContainsRune(ext, 0) {
		return invalidProvisioning("externalId must be 1 to %d characters", maxDeviceExternalIdLen)
	}
	if request.Name != nil && (utf8.RuneCountInString(*request.Name) > maxDeviceNameLen || strings.ContainsRune(*request.Name, 0)) {
		return invalidProvisioning("name must be at most %d characters", maxDeviceNameLen)
	}
	if _, err := rdb.JSONInputOf("metadata", request.Metadata); err != nil {
		return invalidProvisioning("metadata must be valid JSON")
	}
	return nil
}

// provisionDone is what one transaction decided and did.
type provisionDone struct {
	outcome ProvisionOutcome
	device  *Device
}

// provisionOnce is one transaction of ProvisionDevice: lock, decide, write.
func (api *Api) provisionOnce(ctx context.Context, tenant string, request *ProvisionRequest) (*provisionDone, error) {
	var done *provisionDone
	err := api.RDB.DB(ctx).Transaction(func(tx *gorm.DB) error {
		done = nil

		// The profile first: this lock orders every registration against the profile and is
		// first in the lock order every path that touches a profile and a device keeps.
		var profile ProvisioningProfile
		if err := tx.Clauses(clause.Locking{Strength: "UPDATE"}).
			Where("id = ?", request.Profile.ID).First(&profile).Error; err != nil {
			if errors.Is(err, gorm.ErrRecordNotFound) {
				return ErrProvisioningFailed
			}
			return err
		}
		// What was authenticated must still be what is here: a profile disabled, expired or
		// rotated since is refused exactly as an unknown key is.
		if !profileCanRegister(&profile, time.Now()) ||
			profile.ProvisionSecretDigest.String != request.Profile.ProvisionSecretDigest.String {
			return ErrProvisioningFailed
		}

		// The profile's own configuration is the operator's to fix, and nothing is written
		// until it is sound: a strategy outside the vocabulary is never read as ALLOW_NEW, an
		// unmintable credential type never falls back to another, and a deleted device type
		// cannot be stamped onto a device.
		strategy := ProvisioningStrategy(profile.Strategy)
		if !strategy.Valid() {
			log.Error().Str("tenant", tenant).Str("profile", profile.Token).Str("strategy", profile.Strategy).
				Msg("A provisioning profile carries a strategy outside the vocabulary; registrations against it are refused.")
			return ErrProvisioningMisconfigured
		}
		if !provisionableCredentialType(profile.CredentialType) {
			log.Error().Str("tenant", tenant).Str("profile", profile.Token).Str("credentialType", profile.CredentialType).
				Msg("A provisioning profile mints a credential type this build cannot; registrations against it are refused.")
			return ErrProvisioningCredentialTypeUnsupported
		}
		var deviceType DeviceType
		if err := tx.Where("id = ?", profile.DeviceTypeId).First(&deviceType).Error; err != nil {
			if errors.Is(err, gorm.ErrRecordNotFound) {
				log.Error().Str("tenant", tenant).Str("profile", profile.Token).
					Msg("A provisioning profile names a device type that no longer exists; registrations against it are refused.")
				return ErrProvisioningMisconfigured
			}
			return err
		}

		// Then the device, by the name it gives itself.
		var device Device
		err := tx.Clauses(clause.Locking{Strength: "UPDATE"}).
			Where("external_id = ?", request.ExternalId).First(&device).Error
		switch {
		case err == nil:
			d, err := api.decideKnownDevice(ctx, tx, tenant, &profile, &device, request)
			if err != nil {
				return err
			}
			done = d
			return nil
		case !errors.Is(err, gorm.ErrRecordNotFound):
			return err
		}

		// An unknown device.
		if strategy == ProvisionCheckPreProvisioned {
			return ErrProvisioningNotRegistered
		}
		if err := checkProfileCapacity(tx, &profile); err != nil {
			return err
		}
		created, err := createProvisionedDevice(tx, &profile, request)
		if err != nil {
			return err
		}
		if err := api.insertProvisionedCredential(tx, &profile, created, request); err != nil {
			return err
		}
		done = &provisionDone{outcome: ProvisionCreated, device: created}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return done, nil
}

// decideKnownDevice applies steps 1 to 8 to a device that exists, and writes the credential
// only for ADOPT. device is locked.
func (api *Api) decideKnownDevice(ctx context.Context, tx *gorm.DB, tenant string, profile *ProvisioningProfile,
	device *Device, request *ProvisionRequest) (*provisionDone, error) {
	switch {
	case device.IsDisabled():
		return nil, ErrProvisioningDeviceDisabled
	case device.DeviceTypeId != profile.DeviceTypeId:
		return nil, ErrProvisioningTypeMismatch
	case device.ExpectedProvisioningProfileId == nil || *device.ExpectedProvisioningProfileId != profile.ID:
		return nil, ErrProvisioningNotEarmarked
	}

	var held []DeviceCredential
	if err := tx.Where("device_id = ?", device.ID).Order("id ASC").Find(&held).Error; err != nil {
		return nil, err
	}
	now := time.Now()
	var live []DeviceCredential
	foreign := false
	for _, c := range held {
		if c.ProvisioningProfileId == nil || *c.ProvisioningProfileId != profile.ID {
			foreign = true
			continue
		}
		if !c.Enabled || (c.ExpiresAt.Valid && !c.ExpiresAt.Time.After(now)) {
			return nil, ErrProvisioningRevoked
		}
		live = append(live, c)
	}

	// An exact replay of this profile's own issuance. The compare is the Checker's, under the
	// kind that charges nothing to the MQTT connect backoff and keeps no attempt record.
	for _, c := range live {
		stored := c.CredentialId
		err := api.ProvisioningChecker.Check(ctx, credential.Principal{
			Kind: credential.KindProvisionedCredential, ID: tenant + ":" + device.Token, Tenant: tenant,
		}, request.CredentialSecret, func(context.Context) (string, error) { return stored, nil })
		switch {
		case err == nil:
			return &provisionDone{outcome: ProvisionReplayed, device: device}, nil
		case !errors.Is(err, credential.ErrMismatch):
			return nil, err
		}
	}
	if len(live) > 0 || foreign {
		return nil, ErrProvisioningAlreadyProvisioned
	}

	if err := checkProfileCapacity(tx, profile); err != nil {
		return nil, err
	}
	if err := api.insertProvisionedCredential(tx, profile, device, request); err != nil {
		return nil, err
	}
	return &provisionDone{outcome: ProvisionAdopted, device: device}, nil
}

// checkProfileCapacity refuses a registration that would take the profile past its
// maxDevices. It counts under the profile's lock, which is the only reason the count is exact.
func checkProfileCapacity(tx *gorm.DB, profile *ProvisioningProfile) error {
	if profile.MaxDevices == nil {
		return nil
	}
	n, err := provisionedDeviceCount(tx, profile.ID)
	if err != nil {
		return err
	}
	if n >= int64(*profile.MaxDevices) {
		return ErrProvisioningLimitExceeded
	}
	return nil
}

// createProvisionedDevice inserts the device an ALLOW_NEW registration brings into existence:
// the profile's type, earmarked for the profile, under the token derived from its external id.
// A token that another device already holds is ErrProvisioningTokenCollision.
func createProvisionedDevice(tx *gorm.DB, profile *ProvisioningProfile, request *ProvisionRequest) (*Device, error) {
	token := core.DeriveDeviceToken(request.ExternalId, provisionedDeviceTokenPrefix)
	var holder Device
	err := tx.Clauses(clause.Locking{Strength: "UPDATE"}).Where("token = ?", token).First(&holder).Error
	switch {
	case err == nil:
		return nil, ErrProvisioningTokenCollision
	case !errors.Is(err, gorm.ErrRecordNotFound):
		return nil, err
	}
	metadata, err := rdb.JSONInputOf("metadata", request.Metadata)
	if err != nil {
		return nil, invalidProvisioning("metadata must be valid JSON")
	}
	id := profile.ID
	device := &Device{
		TokenReference:                rdb.TokenReference{Token: token},
		ExternalReference:             rdb.ExternalReference{ExternalId: rdb.NullStrOf(&request.ExternalId)},
		NamedEntity:                   rdb.NamedEntity{Name: rdb.NullStrOf(request.Name)},
		MetadataEntity:                rdb.MetadataEntity{Metadata: metadata},
		DeviceTypeId:                  profile.DeviceTypeId,
		ExpectedProvisioningProfileId: &id,
	}
	if err := tx.Create(device).Error; err != nil {
		return nil, err
	}
	return device, nil
}

// insertProvisionedCredential writes the credential a registration issues: an ACCESS_TOKEN
// whose id is the digest of the device's own material, stamped with the profile that issued
// it. The device row is already written, so the credential is inserted by its id and never
// through the association (which would upsert the device again).
func (api *Api) insertProvisionedCredential(tx *gorm.DB, profile *ProvisioningProfile, device *Device,
	request *ProvisionRequest) error {
	cred, err := buildDeviceCredential(api.DeviceSecretKey, device, &DeviceCredentialCreateRequest{
		Token:          core.DeriveDeviceToken(request.ExternalId, provisionedCredentialTokenPrefix),
		DeviceToken:    device.Token,
		CredentialType: string(CredentialAccessToken),
		CredentialId:   request.CredentialSecret,
		Enabled:        true,
	})
	if err != nil {
		return err
	}
	id := profile.ID
	cred.ProvisioningProfileId = &id
	return tx.Omit("Device").Create(cred).Error
}

// classifyProvisionConflict is the answer to a unique violation that survived its retry. The
// constraint decides it: a taken device token is a token collision, anything touching a
// credential is "already provisioned", and the rest (an external id another profile registered
// between the two attempts) is too. It is logged, since it should be rare.
func classifyProvisionConflict(tenant string, request *ProvisionRequest, err error) error {
	constraint := ""
	if ce, ok := conflict.As(err); ok {
		constraint = ce.Constraint
	}
	log.Warn().Str("tenant", tenant).Str("profile", request.Profile.Token).Str("constraint", constraint).
		Msg("A device self-registration hit a unique violation twice in a row.")
	if strings.Contains(constraint, "devices_tenant_token") {
		return ErrProvisioningTokenCollision
	}
	return ErrProvisioningAlreadyProvisioned
}

// mapProvisionError leaves a refusal alone and folds a tenant being erased into the generic
// authentication failure; anything else is an internal error for the caller to report as such.
func mapProvisionError(err error) error {
	var refusal *ProvisioningRefusal
	switch {
	case errors.As(err, &refusal):
		return refusal
	case errors.Is(err, rdb.ErrTenantPurged):
		return ErrProvisioningFailed
	default:
		return err
	}
}

// ValidateProvisionRequest checks everything about a registration that its own fields decide,
// without a transaction or an authenticated profile: the material's format, the external id
// and the optional name and metadata. The HTTP endpoint calls it before it takes a slot, so
// a malformed request costs no more than reading and parsing its body; ProvisionDevice runs
// the same check again, so a caller that skips this still cannot register anything invalid.
func ValidateProvisionRequest(request *ProvisionRequest) error {
	if request == nil {
		return invalidProvisioning("a registration needs a request")
	}
	return validateProvisionRequest(request)
}

// RefuseProvisioning is AuthenticateProvisioningProfile for a request the caller already
// knows cannot succeed, such as one aimed at a tenant that is being deleted: it pays the same
// dummy compare an unknown key pays and answers ErrProvisioningFailed. It exists so that
// refusing early does not make the refusal faster than the others, which would tell a stranger
// which tenants are gone.
func (api *Api) RefuseProvisioning(ctx context.Context, provisionKey, secret string) error {
	if api.ProvisioningChecker == nil || api.EnrollmentKeys == nil {
		return ErrProvisioningUnavailable
	}
	tenant, err := ctxTenant(ctx)
	if err != nil {
		return err
	}
	err = api.ProvisioningChecker.Check(ctx, credential.Principal{
		Kind: credential.KindProvisioningProfile, ID: tenant + ":" + provisionKey, Tenant: tenant,
	}, secret, func(context.Context) (string, error) { return "", nil })
	if err == nil || errors.Is(err, credential.ErrMismatch) {
		return ErrProvisioningFailed
	}
	return err
}
