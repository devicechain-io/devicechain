/// <reference types="node" />

// The replay is not Sitepulse's: it plays whatever recording it is given on the board that recording names. These tests play a Towerpulse recording on
// the Towerpulse operator board with NO board URL from the host, which is the generalisation: the board file comes from the recording's own header.

import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import ReplayApp from './App';
import { setReplayLocale } from './i18n/config';
import { ReplayLoadError, boardBesideRecording, loadReplay, sha256Hex } from './load';
import { ORIGIN, RECORDING_URL, bufferToArrayBuffer, manualTicker, stubFetch } from './testing/harness';

const FRONTEND = path.resolve(import.meta.dirname, '../../..');
const BOARD = readFileSync(path.join(FRONTEND, 'testdata/sim-dashboards/tp-dashboard.json'));
const FIXTURE = JSON.parse(readFileSync(path.join(FRONTEND, 'testdata/board-replay/towerpulse-fixture.json'), 'utf-8'));
const TP_BOARD_URL = `${ORIGIN}/assets/tp-dashboard.json`;

// The committed fixture pins a placeholder board hash (it is a converter output, kept stable while the board is regenerated by the scenario's own
// tests); the pin is re-pointed at the board on disk, in memory, exactly as the Sitepulse suites do.
async function fixtureText(mutate?: (doc: Record<string, any>) => void): Promise<string> {
  const doc = structuredClone(FIXTURE);
  doc.board = { ...doc.board, sha256: await sha256Hex(bufferToArrayBuffer(BOARD)) };
  mutate?.(doc);
  return JSON.stringify(doc);
}

const settle = () =>
  act(async () => {
    await new Promise((r) => setTimeout(r, 30));
  });

beforeEach(async () => {
  await setReplayLocale('en');
});
afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
});

describe('boardBesideRecording', () => {
  const rec = (p: string) => ({ board: { path: p } }) as never;

  it('takes only the file name of the recording-named board and puts it beside the recording', () => {
    expect(boardBesideRecording(RECORDING_URL, rec('frontend/testdata/sim-dashboards/tp-dashboard.json'))).toBe(TP_BOARD_URL);
    expect(boardBesideRecording(`${ORIGIN}/a/b/run.json`, rec('x/sp-dashboard.json'))).toBe(`${ORIGIN}/a/b/sp-dashboard.json`);
  });

  it.each(['x/..', 'x/board.html', 'x/', '', 'x/.json', 'x/a b.json', '..%2Fx.json'])('refuses %j rather than fetching it', (p) => {
    expect(() => boardBesideRecording(RECORDING_URL, rec(p))).toThrow(ReplayLoadError);
  });
});

describe('a Towerpulse recording on the Towerpulse board', () => {
  it('loads with no board URL: the board is the one the recording names, beside it', async () => {
    const stub = stubFetch({ [RECORDING_URL]: await fixtureText(), [TP_BOARD_URL]: BOARD });
    const loaded = await loadReplay({ recordingUrl: RECORDING_URL, fetchFn: stub.fetchFn, origin: ORIGIN });
    expect(stub.calls).toEqual([RECORDING_URL, TP_BOARD_URL]);
    expect(loaded.definition.widgets.map((w) => w.id)).toContain('tp-alarms');
    expect(loaded.recording.devices.map((d) => d.id)).toContain('TP-VAV-T-F4-E');
  });

  it('an explicit board URL still wins over the recording', async () => {
    const other = `${ORIGIN}/elsewhere/tp.json`;
    const stub = stubFetch({ [RECORDING_URL]: await fixtureText(), [other]: BOARD });
    await loadReplay({ recordingUrl: RECORDING_URL, boardUrl: other, fetchFn: stub.fetchFn, origin: ORIGIN });
    expect(stub.calls).toEqual([RECORDING_URL, other]);
  });

  it('refuses to show the recording on a board it was not pinned to', async () => {
    const stub = stubFetch({ [RECORDING_URL]: await fixtureText((d) => (d.board.sha256 = 'f'.repeat(64))), [TP_BOARD_URL]: BOARD });
    await expect(loadReplay({ recordingUrl: RECORDING_URL, fetchFn: stub.fetchFn, origin: ORIGIN })).rejects.toMatchObject({ code: 'boardMismatch' });
  });

  it('refuses a recording whose header names a board file that is not a plain JSON name', async () => {
    const stub = stubFetch({ [RECORDING_URL]: await fixtureText((d) => (d.board.path = 'frontend/testdata/../../etc/passwd')) });
    const err = await loadReplay({ recordingUrl: RECORDING_URL, fetchFn: stub.fetchFn, origin: ORIGIN }).catch((e: unknown) => e);
    expect(err).toBeInstanceOf(ReplayLoadError);
    expect(stub.calls, 'nothing past the recording was fetched').toEqual([RECORDING_URL]);
  });

  it('plays the run: at 7 minutes F4-East reads its recorded temperature and the alarm table lists the zone-hot alarm', async () => {
    const stub = stubFetch({ [RECORDING_URL]: await fixtureText(), [TP_BOARD_URL]: BOARD });
    render(<ReplayApp recordingUrl={RECORDING_URL} boardUrl={null} fetchFn={stub.fetchFn} origin={ORIGIN} ticker={manualTicker()} />);
    await screen.findByTestId('transport-bar');
    await settle();
    const range = document.querySelector('input[type="range"]') as HTMLInputElement;
    // step 14 of the fixture (30 s each, from t=1 s): the alarm raised at step 10 is active, the zone reads hot_temp(14)
    await act(async () => {
      fireEvent.change(range, { target: { value: String(1000 + 14 * 30_000 + 5_000) } });
      fireEvent.pointerUp(range);
    });
    await settle();
    const table = document.querySelector('[data-widget="tp-alarms"]');
    const rows = [...(table?.querySelectorAll('tbody tr') ?? [])].map((r) => r.textContent ?? '');
    expect(rows).toHaveLength(1);
    expect(rows[0]).toContain('tp-vav-tower-f4-east');
    expect(rows[0]).toContain('zone-hot');
    expect(rows[0]).toContain('Major');
    const temp = document.querySelector('[data-widget="tp-zone-temp"] [data-level-readout]')?.textContent ?? '';
    expect(temp).toContain('27.2');
  });
});
