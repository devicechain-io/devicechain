package bootstrap

import (
	"encoding/json"
	"flag"
	"os"
	"path/filepath"
	"testing"
)

var updateSizeGolden = flag.Bool("update-size-golden", false, "rewrite testdata/size_base_golden.json")

// baseGoldenRows are the shapes whose rendering the size axis must not move: every combination of
// --ha and --compact on the default profile, and the two other area sets.
var baseGoldenRows = map[string]func() *State{
	"default":     func() *State { return persistenceState(false, false, "default") },
	"ha":          func() *State { return persistenceState(true, false, "default") },
	"compact":     func() *State { return persistenceState(false, true, "default") },
	"ha-compact":  func() *State { return persistenceState(true, true, "default") },
	"full":        func() *State { return persistenceState(false, false, "full") },
	"telemetry":   func() *State { return persistenceState(false, false, "telemetry") },
	"ingest-only": func() *State { return persistenceState(false, false, "ingest-only") },
	"default-live-vo": func() *State {
		st := persistenceState(false, false, "default")
		st.LiveVolumes = liveVolumesForGolden()
		return st
	},
}

func liveVolumesForGolden() liveVolumes { return liveVolumes{JetStream: "16Gi", EventStore: "64Gi"} }

// baseGolden is what dcctl renders for each row: the chart values and the OpenTofu variables.
func baseGolden(t *testing.T) map[string]interface{} {
	t.Helper()
	out := map[string]interface{}{}
	for name, mk := range baseGoldenRows {
		st := mk()
		out[name] = map[string]interface{}{
			"helmValues": helmValues(st),
			"infraVars":  infraVars(st),
		}
	}
	return out
}

// TestBaseSizeIsTodaysRender pins the compat guarantee of the size axis: an instance that names no
// size, or names base, renders byte for byte what dcctl rendered before the axis existed. The
// golden was generated by the code BEFORE the axis was added (git stash of the change), so it
// cannot have been written to agree with it. Regenerate only with -update-size-golden and only for
// a deliberate change to the base render.
func TestBaseSizeIsTodaysRender(t *testing.T) {
	got, err := json.MarshalIndent(baseGolden(t), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join("testdata", "size_base_golden.json")
	if *updateSizeGolden {
		if err := os.WriteFile(path, append(got, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(append(got, '\n')) != string(want) {
		t.Errorf("the base render moved. The size axis must not change what an instance that names " +
			"no size renders; if this change is deliberate, regenerate with -update-size-golden and say so in the release notes")
	}
}
