func TestCreateIntegrationReturnsTheTokenOnceAndStoresOnlyItsDigest(t *testing.T) {
	f := newIntFixture(t)
	created := f.create("chirp-1")

	require.Len(t, created.IssuedToken, 43, "256 bits, base64url without padding")
	assert.Equal(t, IntegrationIdentityDevEUI, created.Identity, "a network-server type defaults to DEV_EUI")
	assert.False(t, created.LinkMetrics)
	require.Len(t, created.DeviceTypes, 1)

	// The row read back carries no token, and the stored column is a digest of it.
	rows, err := f.api.IntegrationsByToken(f.ctx, []string{"chirp-1"})
	require.NoError(t, err)
	require.Len(t, rows, 1)
	assert.Empty(t, rows[0].IssuedToken)
	assert.NotContains(t, rows[0].TokenDigest, created.IssuedToken)
	assert.True(t, strings.HasPrefix(rows[0].TokenDigest, "v1$"+testEnrollmentKeys.Integration.KeyId()+"$"),
		"the digest is under the integration key: %q", rows[0].TokenDigest)
	assert.False(t, rows[0].TokenIssuedAt.IsZero())

	// A second integration gets a different token.
	other := f.create("chirp-2")
	assert.NotEqual(t, created.IssuedToken, other.IssuedToken)
}

func TestAuthenticateIntegration(t *testing.T) {
	f := newIntFixture(t)
	created := f.create("chirp-1")

	got, err := f.api.AuthenticateIntegration(f.ctx, "chirp-1", created.IssuedToken)
	require.NoError(t, err, "the paired positive: the issued token authenticates")
	assert.Equal(t, "chirp-1", got.Token)
	require.Len(t, got.DeviceTypes, 1, "the scope comes with it")
	assert.Equal(t, "dt-a", got.DeviceTypes[0].Token)

	// Every failure is one answer.
	for name, call := range map[string]func() error{
		"wrong token": func() error {
			_, err := f.api.AuthenticateIntegration(f.ctx, "chirp-1", differentToken(created.IssuedToken))
			return err
		},
		"empty token": func() error {
			_, err := f.api.AuthenticateIntegration(f.ctx, "chirp-1", "")
			return err
		},
		"oversized token": func() error {
			_, err := f.api.AuthenticateIntegration(f.ctx, "chirp-1", strings.Repeat("a", credential.MaxEnrollmentSecretBytes+1))
			return err
		},
		"unknown integration": func() error {
			_, err := f.api.AuthenticateIntegration(f.ctx, "nope", created.IssuedToken)
			return err
		},
		"another tenant": func() error {
			_, err := f.api.AuthenticateIntegration(core.WithTenant(context.Background(), "globex"), "chirp-1", created.IssuedToken)
			return err
		},
	} {
		assert.ErrorIs(t, call(), ErrIntegrationAuthFailed, name)
	}
}

// The work does not say whether the integration exists: an unknown one is compared against the
// Checker's dummy, so every failing request pays exactly one compare.
func TestAuthenticateIntegrationFailsUniformlyAndPaysTheSameCompare(t *testing.T) {
	f := newIntFixture(t)
	created := f.create("chirp-1")

	for name, call := range map[string]func() error{
		"wrong token on a known integration": func() error {
			_, err := f.api.AuthenticateIntegration(f.ctx, "chirp-1", "wrong-"+created.IssuedToken)
			return err
		},
		"any token on an unknown integration": func() error {
			_, err := f.api.AuthenticateIntegration(f.ctx, "nope", created.IssuedToken)
			return err
		},
	} {
		*f.seen = (*f.seen)[:0]
		require.ErrorIs(t, call(), ErrIntegrationAuthFailed, name)
		assert.Len(t, *f.seen, 1, "%s: exactly one compare is paid", name)
	}
	// The unknown integration's compare is the dummy, a digest of the integration kind.
	*f.seen = (*f.seen)[:0]
	_, _ = f.api.AuthenticateIntegration(f.ctx, "nope", "x")
	require.Len(t, *f.seen, 1)
	assert.NoError(t, testEnrollmentKeys.Integration.Recognizes(string((*f.seen)[0])))
}

func TestRotateIntegrationToken(t *testing.T) {
	f := newIntFixture(t)
	first := f.create("chirp-1")

	rotated, err := f.api.RotateIntegrationToken(f.ctx, "chirp-1")
	require.NoError(t, err)
	require.Len(t, rotated.IssuedToken, 43)
	assert.NotEqual(t, first.IssuedToken, rotated.IssuedToken)

	_, err = f.api.AuthenticateIntegration(f.ctx, "chirp-1", first.IssuedToken)
	assert.ErrorIs(t, err, ErrIntegrationAuthFailed, "the old token stops working at once")
	_, err = f.api.AuthenticateIntegration(f.ctx, "chirp-1", rotated.IssuedToken)
	assert.NoError(t, err, "the control: the new token works")

	_, err = f.api.RotateIntegrationToken(f.ctx, "nope")
	assert.ErrorIs(t, err, gorm.ErrRecordNotFound)

	// An edit never touches the token.
	_, err = f.api.UpdateIntegration(f.ctx, "chirp-1", &IntegrationUpdateRequest{Name: dcgraphql.OptionalStringOf("renamed")})
	require.NoError(t, err)
	_, err = f.api.AuthenticateIntegration(f.ctx, "chirp-1", rotated.IssuedToken)
	assert.NoError(t, err, "an update left the token alone")
}

// A disabled integration is not authenticated, and is reported as disabled only to a caller that
// holds its token.
func TestAuthenticateIntegrationRefusesADisabledOne(t *testing.T) {
	f := newIntFixture(t)
	created := f.create("chirp-1")
	_, err := f.api.UpdateIntegration(f.ctx, "chirp-1", &IntegrationUpdateRequest{Enabled: dcgraphql.OptionalBoolOf(false)})
	require.NoError(t, err)

	got, err := f.api.AuthenticateIntegration(f.ctx, "chirp-1", created.IssuedToken)
	assert.ErrorIs(t, err, ErrIntegrationDisabled)
	require.NotNil(t, got, "the integration comes back with the refusal so a caller can say why")
	assert.False(t, got.Enabled)

	_, err = f.api.AuthenticateIntegration(f.ctx, "chirp-1", differentToken(created.IssuedToken))
	assert.ErrorIs(t, err, ErrIntegrationAuthFailed, "without the token a disabled integration looks like any other failure")

	// The control: enabling it again authenticates.
	_, err = f.api.UpdateIntegration(f.ctx, "chirp-1", &IntegrationUpdateRequest{Enabled: dcgraphql.OptionalBoolOf(true)})
	require.NoError(t, err)
	_, err = f.api.AuthenticateIntegration(f.ctx, "chirp-1", created.IssuedToken)
	assert.NoError(t, err)
}

