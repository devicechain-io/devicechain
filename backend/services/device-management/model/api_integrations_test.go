// A caller whose access is limited to part of the tenant reads no integration: the model
// declares no scope rule, so the store refuses the read whatever a resolver does.
func TestIntegrationsAreRefusedToAScopedCaller(t *testing.T) {
	f := newIntFixture(t)
	f.create("chirp-1")

	scoped := auth.WithClaims(f.ctx, &auth.Claims{TokenType: auth.TokenTypeAccess,
		Authorities: []string{string(auth.DeviceRead)}, ScopeAnchors: []string{"customer:acme"}})
	_, err := f.api.IntegrationsByToken(scoped, []string{"chirp-1"})
	require.ErrorIs(t, err, auth.ErrScopeUnsupported)
	_, err = f.api.Integrations(scoped, IntegrationSearchCriteria{})
	require.ErrorIs(t, err, auth.ErrScopeUnsupported)

	// Each table on its own, so a rule declared on one cannot hide behind the refusal of the
	// other (the API reads the scope rows second).
	var integrations []Integration
	require.ErrorIs(t, f.api.RDB.DB(scoped).Find(&integrations).Error, auth.ErrScopeUnsupported,
		"the integrations table itself declares no scope rule")
	var scope []IntegrationDeviceType
	require.ErrorIs(t, f.api.RDB.DB(scoped).Find(&scope).Error, auth.ErrScopeUnsupported,
		"the scope rows declare none either")

	unscoped := auth.WithClaims(f.ctx, &auth.Claims{TokenType: auth.TokenTypeAccess,
		Authorities: []string{string(auth.DeviceRead)}})
	rows, err := f.api.IntegrationsByToken(unscoped, []string{"chirp-1"})
	require.NoError(t, err, "the control: the same claims without a scope read it")
	assert.Len(t, rows, 1)
}

// Integration writes are journaled by construction, like every control-plane entity: who
// changed which integration, labelled by its token, and never the token's value or digest.
func TestIntegrationWritesAreAudited(t *testing.T) {
	f := newIntFixture(t)
	require.NoError(t, rdb.RegisterAuditJournal(f.api.RDB.Database))

	created := f.create("chirp-1")
	rotated, err := f.api.RotateIntegrationToken(f.ctx, "chirp-1")
	require.NoError(t, err)
	_, err = f.api.UpdateIntegration(f.ctx, "chirp-1", &IntegrationUpdateRequest{Name: dcgraphql.OptionalStringOf("renamed")})
	require.NoError(t, err)
	removed, err := f.api.DeleteIntegration(f.ctx, "chirp-1")
	require.NoError(t, err)
	require.True(t, removed)

	var rows []rdb.AuditEvent
	require.NoError(t, f.api.RDB.DB(f.ctx).Order("id").Find(&rows).Error)
	ops := map[string]int{}
	for _, r := range rows {
		if r.TableName != "integrations" {
			continue
		}
		ops[r.Operation]++
		if r.Operation != "delete" {
			assert.Equal(t, "chirp-1", r.EntityLabel, "%s is labelled by the integration's token", r.Operation)
		}
		for _, secret := range []string{created.IssuedToken, rotated.IssuedToken, rotated.TokenDigest} {
			assert.NotContains(t, r.EntityLabel+r.EntityPK+r.Actor, secret, "the journal is metadata-only")
		}
	}
	assert.Equal(t, 1, ops["create"], "create")
	assert.GreaterOrEqual(t, ops["update"], 2, "the rotation and the edit are both updates")
	assert.Equal(t, 1, ops["delete"], "delete")
}

// differentToken returns a token of the same shape that is certainly not the one given. Issued
// tokens are random base64url, so "overwrite the first character with a fixed one" is the
// original again one time in 64.
func differentToken(token string) string {
	first := byte('A')
	if token[0] == first {
		first = 'B'
	}
	return string(first) + token[1:]
}
