func TestIntegrationsCeiling(t *testing.T) {
	f := newIntFixture(t)

	// No resolver wired: the platform default, never unbounded.
	for i := 0; i < governance.DefaultIntegrationsPerTenant; i++ {
		f.create("default-" + string(rune('a'+i)))
	}
	_, err := f.api.CreateIntegration(f.ctx, &IntegrationCreateRequest{
		Token: "one-too-many", Type: string(IntegrationChirpStackV4), Enabled: true, DeviceTypeTokens: []string{"dt-a"}})
	le, ok := limit.As(err)
	require.True(t, ok, "the refusal is LIMIT_EXCEEDED: %v", err)
	assert.Equal(t, governance.DefaultIntegrationsPerTenant, le.Max)

	// The tier raises it: the control for the refusal above.
	f.api.IntegrationsCeiling = ceilingStub{n: governance.DefaultIntegrationsPerTenant + 1}
	f.create("one-more")
	_, err = f.api.CreateIntegration(f.ctx, &IntegrationCreateRequest{
		Token: "again", Type: string(IntegrationChirpStackV4), Enabled: true, DeviceTypeTokens: []string{"dt-a"}})
	_, ok = limit.As(err)
	assert.True(t, ok, "the raised ceiling is enforced too: %v", err)

	// A tier that holds none.
	f2 := newIntFixture(t)
	f2.api.IntegrationsCeiling = ceilingStub{n: 0}
	_, err = f2.api.CreateIntegration(f2.ctx, &IntegrationCreateRequest{
		Token: "x", Type: string(IntegrationChirpStackV4), Enabled: true, DeviceTypeTokens: []string{"dt-a"}})
	_, ok = limit.As(err)
	assert.True(t, ok, "a ceiling of zero admits nothing: %v", err)
}

