//go:generate go run ../cmd/instance-config-schema -output instance-config.schema.json

//go:embed instance-config.schema.json
var instanceSchema []byte

// InstanceJSONSchema returns the schema shipped with this build. Release assets
// and dcctl serve these same bytes; callers receive a copy so they cannot change it.
func InstanceJSONSchema() []byte { return bytes.Clone(instanceSchema) }

// GenerateInstanceJSONSchema derives the structural document contract from the
// Go decoding types. It deliberately does not duplicate ApplyDefaults/Validate:
// semantic, cross-field and environment checks remain the startup loader's job.
// Unsupported shapes fail generation rather than silently becoming permissive.
func GenerateInstanceJSONSchema() ([]byte, error) {
	b := schemaBuilder{defs: map[string]any{}}
	root, err := b.node(reflect.TypeFor[InstanceConfiguration]())
	if err != nil {
		return nil, err
	}
	retired := (&InstanceConfiguration{}).RetiredConfigKeys()
	paths := make([]string, 0, len(retired))
	for path := range retired {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		if err := b.retire(root, strings.Split(path, "."), retired[path]); err != nil {
			return nil, err
		}
	}
	root["$schema"] = "https://json-schema.org/draft/2020-12/schema"
	root["$defs"] = b.defs
	root["title"] = "DeviceChain instance configuration"
	root["$comment"] = "Copyright The DeviceChain Authors; SPDX-License-Identifier: Apache-2.0; generated by go generate ./config; DO NOT EDIT"
	root["description"] = "Structural schema of the instance document mounted at /etc/dci-config/instance. Use the asset from the exact target release or that release's dcctl config-schema. Keys match case-insensitively, omitted values are defaulted at startup, and declared retired keys are ignored with a warning. Startup validation additionally enforces semantic and cross-field constraints. Datastore configuration maps remain open because their keys depend on the selected driver."
	raw, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(raw, '\n'), nil
}

// CheckInstanceJSONSchema is the generator's read-only CI mode. Compare bytes,
// including formatting, so the checked-in artifact has one deterministic form.
func CheckInstanceJSONSchema(committed []byte) error {
	want, err := GenerateInstanceJSONSchema()
	if err != nil {
		return err
	}
	if !bytes.Equal(committed, want) {
		return fmt.Errorf("instance config schema drift: run go generate ./config from backend/core")
	}
	return nil
}

type schemaBuilder struct{ defs map[string]any }

func (b *schemaBuilder) node(t reflect.Type) (map[string]any, error) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	// None of today's instance types has a custom codec. Require an explicit
	// implementation if that changes; reflecting its fields would lie about its wire shape.
	for _, codec := range []reflect.Type{
		reflect.TypeFor[json.Marshaler](), reflect.TypeFor[json.Unmarshaler](),
		reflect.TypeFor[encoding.TextMarshaler](), reflect.TypeFor[encoding.TextUnmarshaler](),
	} {
		if t.Implements(codec) || reflect.PointerTo(t).Implements(codec) {
			return nil, fmt.Errorf("instance schema: custom codec on %s needs explicit support", t)
		}
	}
	nullable := func(kind string) map[string]any {
		// encoding/json accepts null even for value fields (it leaves them unchanged).
		return map[string]any{"type": []string{kind, "null"}}
	}
	switch t.Kind() {
	case reflect.Struct:
		name := t.Name()
		if name == "" || t.PkgPath() != reflect.TypeFor[InstanceConfiguration]().PkgPath() {
			return nil, fmt.Errorf("instance schema: unsupported struct %s", t)
		}
		ref := map[string]any{"$ref": "#/$defs/" + name}
		if _, ok := b.defs[name]; ok {
			return ref, nil
		}
		n := nullable("object")
		props, patterns := map[string]any{}, map[string]any{}
		n["properties"], n["patternProperties"] = props, patterns
		n["additionalProperties"] = false
		b.defs[name] = n
		for i := 0; i < t.NumField(); i++ {
			field := t.Field(i)
			if !field.IsExported() {
				continue
			}
			tag := strings.Split(field.Tag.Get("json"), ",")
			if tag[0] == "-" {
				continue
			}
			if field.Anonymous || strings.Contains(field.Tag.Get("json"), ",string") {
				return nil, fmt.Errorf("instance schema: embedded or string-encoded field %s.%s needs explicit support", t, field.Name)
			}
			name := tag[0]
			if name == "" {
				name = strings.ToLower(field.Name[:1]) + field.Name[1:]
			}
			child, err := b.node(field.Type)
			if err != nil {
				return nil, err
			}
			props[name], patterns[foldedKeyPattern(name)] = child, child
		}
		return ref, nil
	case reflect.Map:
		n := nullable("object")
		child, err := b.node(t.Elem())
		if err != nil {
			return nil, err
		}
		n["additionalProperties"] = child
		switch t.Key().Kind() {
		case reflect.String:
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
			n["propertyNames"] = map[string]any{"pattern": "^[+-]?[0-9]+$"}
		default:
			return nil, fmt.Errorf("instance schema: unsupported map key %s", t.Key())
		}
		return n, nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return nil, fmt.Errorf("instance schema: byte encoding %s needs explicit support", t)
		}
		n := nullable("array")
		child, err := b.node(t.Elem())
		if err != nil {
			return nil, err
		}
		n["items"] = child
		if t.Kind() == reflect.Array {
			n["minItems"], n["maxItems"] = t.Len(), t.Len()
		}
		return n, nil
	case reflect.Interface:
		if t.NumMethod() != 0 {
			return nil, fmt.Errorf("instance schema: unsupported interface %s", t)
		}
		return map[string]any{}, nil
	case reflect.String:
		return nullable("string"), nil
	case reflect.Bool:
		return nullable("boolean"), nil
	case reflect.Float32, reflect.Float64:
		return nullable("number"), nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		n := nullable("integer")
		n["minimum"], n["maximum"] = -(int64(1) << (t.Bits() - 1)), int64(1)<<(t.Bits()-1)-1
		return n, nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		n := nullable("integer")
		n["minimum"], n["maximum"] = 0, ^uint64(0)>>(64-t.Bits())
		return n, nil
	default:
		return nil, fmt.Errorf("instance schema: unsupported type %s", t)
	}
}

// JSON Schema regular expressions have no portable case-insensitive flag.
// SimpleFold includes the non-ASCII equivalents encoding/json also accepts.
func foldedKeyPattern(name string) string {
	var out strings.Builder
	out.WriteByte('^')
	for _, c := range name {
		if c >= 'A' && c <= 'Z' {
			c += 'a' - 'A'
		}
		if c >= 'a' && c <= 'z' {
			out.WriteByte('[')
			out.WriteRune(c)
			for next := unicode.SimpleFold(c); next != c; next = unicode.SimpleFold(next) {
				out.WriteRune(next)
			}
			out.WriteByte(']')
		} else {
			out.WriteString(regexp.QuoteMeta(string(c)))
		}
	}
	out.WriteByte('$')
	return out.String()
}

func (b *schemaBuilder) retire(n map[string]any, path []string, guidance string) error {
	if ref, ok := n["$ref"].(string); ok {
		n = b.defs[strings.TrimPrefix(ref, "#/$defs/")].(map[string]any)
	}
	props, ok := n["properties"].(map[string]any)
	if !ok {
		return fmt.Errorf("instance schema: retired path %s has no object parent", strings.Join(path, "."))
	}
	if len(path) == 1 {
		child := map[string]any{"deprecated": true, "description": "Retired; value is ignored at startup. " + guidance}
		props[path[0]] = child
		n["patternProperties"].(map[string]any)[foldedKeyPattern(path[0])] = child
		return nil
	}
	for name, child := range props {
		if strings.EqualFold(name, path[0]) {
			return b.retire(child.(map[string]any), path[1:], guidance)
		}
	}
	return fmt.Errorf("instance schema: retired path parent %s is missing", path[0])
}
