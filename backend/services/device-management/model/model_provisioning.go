// ProvisioningStrategy decides whether a self-registration request may bring a
// brand-new device into existence or must match a device the operator
// pre-registered (ADR-012 provisioning policy). The two strategies are
// allow-new vs. check-pre-provisioned.
type ProvisioningStrategy string

const (
	// ProvisionAllowNew creates a device on first contact when none yet exists for
	// the presented external id. Convenient for open fleets that self-register. It
	// never adopts a device that was not earmarked for the profile.
	ProvisionAllowNew ProvisioningStrategy = "ALLOW_NEW"
	// ProvisionCheckPreProvisioned rejects any external id the operator has not already
	// registered AND earmarked for the profile. The locked-down posture: provisioning only
	// mints credentials for devices that were provisioned out of band.
	ProvisionCheckPreProvisioned ProvisioningStrategy = "CHECK_PRE_PROVISIONED"
)

// Valid reports whether the strategy names one of the known strategies.
func (s ProvisioningStrategy) Valid() bool {
	switch s {
	case ProvisionAllowNew, ProvisionCheckPreProvisioned:
		return true
	default:
		return false
	}
}

// String returns the underlying string value.
func (s ProvisioningStrategy) String() string {
	return string(s)
}

// Data required to create a provisioning profile.
//
// There is no ProvisionSecret: the server generates it (256 bits) and returns it once, as the
// created profile's IssuedSecret. A secret an operator chose is a secret somebody else may
// also know, and the endpoint compares it with no per-key backoff because nothing can be
// guessed.
type ProvisioningProfileCreateRequest struct {
	Token        string
	Name         *string
	Description  *string
	ProvisionKey string
	Strategy     string
	// DeviceTypeToken is the type every device the profile registers has, and the only type
	// of device it will adopt.
	DeviceTypeToken string
	// MaxDevices caps how many devices the profile may register. Optional; omitted or null is
	// uncapped. When set it must be at least 1.
	MaxDevices *int32
	// CredentialType is the credential type minted for a provisioned device.
	// Optional; defaults to ACCESS_TOKEN, the only type provisioning mints today
	// (minting MQTT_BASIC credentials is a later onboarding slice).
	CredentialType *string
	Enabled        bool
	ExpiresAt      *string
	Metadata       *string
}

// A PARTIAL update to a provisioning profile: omit a field to leave the stored value
// alone, send null to clear a nullable one, send a value to set it. There is no Token —
// the profile is identified by the mutation's `token` argument.
//
// There is no ProvisionSecret either: the secret is generated by the server and changes only
// through RotateProvisioningProfileSecret, so no edit can blank it or replace it with a
// guessable one. (Under the full-replace shape an edit that changed nothing but the NAME had to
// restate the shared secret the whole fleet presents, and one that did not blanked it.)
//
// # 🔴 credentialType is absent, and the reason is the same one that removes an immutable field
//
// A provisioning profile records which credential type it mints, and today
// provisionableCredentialType admits exactly one value: ACCESS_TOKEN. Create refuses
// anything else, so every stored value is ACCESS_TOKEN, so an update naming the field can
// only restate what is there (a no-op) or name something the check refuses (an error).
// That is the same shape as EntityGroup's memberType, and it gets the same answer: the
// field is not in the input.
//
// The difference from memberType is that this one is a CURRENT limit rather than an
// identity property — minting MQTT_BASIC is a later onboarding slice — and adding
// an optional field back to an input is additive. So this is a removal that reverses
// cleanly on the day a second type becomes mintable, not a decision about the entity.
//
// The full-replace shape it replaces did something worse than any of that: it read a nil
// CredentialType as "use the create-time default", so an edit that changed only the name
// RESET the credential type of every device the profile went on to provision.
type ProvisioningProfileUpdateRequest struct {
	Name        dcgraphql.OptionalString
	Description dcgraphql.OptionalString
	// ProvisionKey names the profile a device registers against, on a NOT NULL column: a
	// blank key authenticates nothing, so it refuses a null.
	ProvisionKey dcgraphql.OptionalString
	// Strategy is a NOT NULL vocabulary column.
	Strategy dcgraphql.OptionalString
	// DeviceTypeToken is stamped onto auto-created devices; the FK is NOT NULL, so a
	// null is refused and an unknown token refuses the whole update.
	DeviceTypeToken dcgraphql.OptionalString
	Enabled         dcgraphql.OptionalBool
	// ExpiresAt is an RFC3339 timestamp on a nullable column: null (or an empty string)
	// means "never expires".
	ExpiresAt dcgraphql.OptionalString
	// MaxDevices is the profile's cap. Omitted keeps it, null removes it (uncapped), a value
	// of at least 1 sets it. Lowering it below the number already registered refuses further
	// registrations; it never removes a device.
	MaxDevices dcgraphql.OptionalInt32
	Metadata   dcgraphql.OptionalString
}

// ProvisioningProfile carries the shared key+secret a fleet presents to
// self-register, the strategy that governs whether unknown devices may be
// created, and the device type stamped onto auto-created devices (ADR-012). A device
// registers by presenting the profile's key and secret to the self-registration operation
// (ProvisionDevice), which is the only reader of the secret.
//
// 🔴 THE SECRET IS NEVER STORED, ONLY ITS KEYED DIGEST. ProvisionSecretDigest is what
// credential.DeriveEnrollmentSecretKeys's key made of the secret that
// CreateProvisioningProfile or RotateProvisioningProfileSecret generated, and NULL for a
// profile with none (which matches no presented secret). Nothing that reads this row can
// recover the secret. The provision_secret column that held the plaintext is still in the
// table, NULLed by DigestPlaintextProvisionSecrets at startup and by every write
// (LegacyProvisionSecret). A presented secret is compared in constant time through the
// credential Checker (AuthenticateProvisioningProfile). It needs no per-key backoff: the
// secret is generated by the server with 256 bits of entropy, so nothing can be guessed
// online, and the endpoint is limited per source and per tenant instead.
//
// 🔴 ProvisionSecretIssued IS WHAT SAYS THE SECRET WAS GENERATED BY THE SERVER. It is set by
// create and rotate and by nothing else. A profile created before the server generated its
// secrets holds an operator-chosen one (its digest was converted from the plaintext), which
// the endpoint refuses until it is rotated: that secret may be known to anyone who ever
// configured the fleet.
type ProvisioningProfile struct {
	gorm.Model
	rdb.TenantScoped
	rdb.TokenReference
	rdb.NamedEntity
	rdb.MetadataEntity

	ProvisionKey          string
	ProvisionSecretDigest sql.NullString
	// ProvisionSecretIssued is true only for a secret the server generated (see above).
	ProvisionSecretIssued bool
	Strategy              string
	DeviceTypeId          uint
	DeviceType            *DeviceType
	CredentialType        string
	Enabled               bool
	ExpiresAt             sql.NullTime
	// MaxDevices is the cap on devices this profile registers, nil for none.
	MaxDevices *int

	// IssuedSecret is the provision secret as generated, on the row a create or a rotate just
	// wrote, and "" on every row read from the database. It is not a column. The response to
	// the write that minted it shows it, once; nothing can show it again.
	IssuedSecret string `gorm:"-"`

	// LegacyProvisionSecret is the retired plaintext column, mapped WRITE-ONLY so that every
	// create and save of a profile writes it NULL. Nothing reads it, and nothing may set it.
	//
	// 🔴 IT IS LOAD-BEARING DURING A ROLLING UPGRADE, for the reason
	// DeviceCredential.LegacyCredentialValue gives: an old-version pod rotates the secret
	// into this column and leaves the digest alone, and a new pod that saved without
	// clearing it would let the next start digest the OLDER value over the newer one.
	LegacyProvisionSecret sql.NullString `gorm:"column:provision_secret;->:false;<-"`
}

// DefaultOrder implements rdb.Sortable with the registry default: newest first, token
// as the unique tiebreak. Note this is NOT ordered by ExpiresAt the way DeviceCredential
// is — nothing reuses a provisioning profile off the front of a page; a profile is
// selected by its ProvisionKey, never by position in a list.
func (ProvisioningProfile) DefaultOrder() string {
	return "provisioning_profiles.created_at DESC, provisioning_profiles.token ASC"
}

// Search criteria for locating provisioning profiles.
type ProvisioningProfileSearchCriteria struct {
	rdb.Pagination
	DeviceType *string
	Strategy   *string
	Enabled    *bool
}

// Results for provisioning profile search.
type ProvisioningProfileSearchResults struct {
	Results    []ProvisioningProfile
	Pagination rdb.SearchResultsPagination
}
